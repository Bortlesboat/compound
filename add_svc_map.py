with open('C:/Projects/AI/compound/src/core/hos/syscall.c','a') as f:
    f.write('\n\nstatic error_t svc_map_memory(hos_syscall_context_t *context, guest_state_t *state)\n{\n')
    f.write('    if(memory_call_needs_layout(context, "svcMapMemory")) return POUND_ERROR_UNSUPPORTED_SYSCALL;\n')
    f.write('    const uint64_t dst_addr = state->x[0];\n')
    f.write('    const uint64_t src_addr = state->x[1];\n')
    f.write('    const uint64_t size = state->x[2];\n')
    f.write('    const uint32_t perm = (uint32_t)state->x[3];\n')
    f.write('    if((dst_addr % HOS_MEMORY_PAGE_SIZE)!=0U||(src_addr % HOS_MEMORY_PAGE_SIZE)!=0U||(size==0U)||(size % HOS_MEMORY_PAGE_SIZE)!=0U){state->x[0]=HOS_RESULT_INVALID_SIZE;return POUND_SUCCESS;}\n')
    f.write('    uint32_t res = HOS_RESULT_SUCCESS;\n')
    f.write('    error_t err = hos_memory_layout_map_alias(context->layout, src_addr, dst_addr, size, HOS_MEMORY_STATE_ALIAS, perm, 0U);\n')
    f.write('    if(!memory_layout_error_to_result(err, &res)){\n')
    f.write('        if(err==POUND_ERROR_INVALID_ARGUMENT) res = HOS_RESULT_INVALID_CURRENT_MEMORY;\n')
    f.write('        else if(err==POUND_ERROR_ALLOCATION_FAILED) res = HOS_RESULT_SLAB_EXHAUSTED;\n')
    f.write('        else if(err==POUND_ERROR_GUEST_ADDRESS_OUT_OF_BOUNDS||err==POUND_ERROR_GUEST_ADDRESS_OVERFLOW) res = HOS_RESULT_INVALID_ADDRESS;\n')
    f.write('        else return err;\n')
    f.write('    }\n')
    f.write('    state->x[0]=res; return POUND_SUCCESS;\n')
    f.write('}\n\n')
    f.write('static error_t svc_unmap_memory(hos_syscall_context_t *context, guest_state_t *state)\n{\n')
    f.write('    if(memory_call_needs_layout(context, "svcUnmapMemory")) return POUND_ERROR_UNSUPPORTED_SYSCALL;\n')
    f.write('    const uint64_t addr = state->x[0];\n')
    f.write('    const uint64_t size = state->x[1];\n')
    f.write('    if((addr % HOS_MEMORY_PAGE_SIZE)!=0U||(size==0U)||(size % HOS_MEMORY_PAGE_SIZE)!=0U){state->x[0]=HOS_RESULT_INVALID_SIZE;return POUND_SUCCESS;}\n')
    f.write('    uint32_t res = HOS_RESULT_SUCCESS;\n')
    f.write('    error_t err = hos_memory_layout_unmap(context->layout, addr, size);\n')
    f.write('    if(!memory_layout_error_to_result(err, &res)){\n')
    f.write('        if(err==POUND_ERROR_INVALID_ARGUMENT) res = HOS_RESULT_INVALID_CURRENT_MEMORY;\n')
    f.write('        else if(err==POUND_ERROR_ALLOCATION_FAILED) res = HOS_RESULT_SLAB_EXHAUSTED;\n')
    f.write('        else if(err==POUND_ERROR_GUEST_ADDRESS_OUT_OF_BOUNDS||err==POUND_ERROR_GUEST_ADDRESS_OVERFLOW) res = HOS_RESULT_INVALID_ADDRESS;\n')
    f.write('        else return err;\n')
    f.write('    }\n')
    f.write('    state->x[0]=res; return POUND_SUCCESS;\n')
    f.write('}\n')
